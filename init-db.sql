CREATE EXTENSION IF NOT EXISTS vector;

CREATE TABLE IF NOT EXISTS users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name TEXT NOT NULL,
    email TEXT NOT NULL UNIQUE,
    role TEXT NOT NULL CHECK (role IN ('administrator', 'manager')),
    password_hash TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS institutions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code TEXT NOT NULL UNIQUE,
    name TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS programs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    institution_id BIGINT NOT NULL REFERENCES institutions (id),
    name TEXT NOT NULL,
    level TEXT NOT NULL,
    UNIQUE (institution_id, name)
);

-- Document catalog. Removing an institution also removes its documents and
-- their dependent versions, jobs, and chunks.
CREATE TABLE IF NOT EXISTS documents (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title TEXT NOT NULL,
    institution_id BIGINT NOT NULL REFERENCES institutions (id) ON DELETE CASCADE,
    source_type TEXT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- Each physical file is retained as a version; only one version per document
-- can be active at a time.
CREATE TABLE IF NOT EXISTS document_versions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    document_id BIGINT NOT NULL REFERENCES documents (id) ON DELETE CASCADE,
    file_path TEXT NOT NULL,
    version_number INTEGER NOT NULL CHECK (version_number > 0),
    is_active BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    UNIQUE (document_id, version_number),
    UNIQUE (document_id, id)
);

CREATE UNIQUE INDEX IF NOT EXISTS uq_document_versions_one_active
    ON document_versions (document_id)
    WHERE is_active;

-- Queue and processing log for the asynchronous Python worker.
CREATE TABLE IF NOT EXISTS sync_jobs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    document_id BIGINT NOT NULL REFERENCES documents (id) ON DELETE CASCADE,
    document_version_id BIGINT,
    operation TEXT NOT NULL CHECK (operation IN ('add', 'update', 'delete')),
    -- Worker lifecycle: pending (En attente), running (En cours),
    -- succeeded (Succès), failed (Erreur).
    status TEXT NOT NULL DEFAULT 'pending'
        CHECK (status IN ('pending', 'running', 'succeeded', 'failed')),
    error_message TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    started_at TIMESTAMPTZ,
    completed_at TIMESTAMPTZ,
    FOREIGN KEY (document_id, document_version_id)
        REFERENCES document_versions (document_id, id) ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS ix_sync_jobs_pending
    ON sync_jobs (created_at, id)
    WHERE status = 'pending';

CREATE INDEX IF NOT EXISTS ix_sync_jobs_document_id
    ON sync_jobs (document_id);

-- Embedding dimensions must match the model used by the Python worker.
-- This schema uses 1536 dimensions (for example, text-embedding-3-small).
CREATE TABLE IF NOT EXISTS document_chunks (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    document_version_id BIGINT NOT NULL
        REFERENCES document_versions (id) ON DELETE CASCADE,
    chunk_index INTEGER NOT NULL CHECK (chunk_index >= 0),
    content TEXT NOT NULL,
    page_number INTEGER CHECK (page_number IS NULL OR page_number > 0),
    vecteur vector(1536) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    UNIQUE (document_version_id, chunk_index)
);

CREATE INDEX IF NOT EXISTS ix_document_chunks_version_id
    ON document_chunks (document_version_id);

CREATE INDEX IF NOT EXISTS ix_document_chunks_vecteur_hnsw
    ON document_chunks USING hnsw (vecteur vector_cosine_ops);

-- Keep modification timestamps current for the document pipeline tables.
CREATE OR REPLACE FUNCTION set_updated_at()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
    NEW.updated_at = NOW();
    RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_documents_updated_at ON documents;
CREATE TRIGGER trg_documents_updated_at
    BEFORE UPDATE ON documents
    FOR EACH ROW EXECUTE FUNCTION set_updated_at();

DROP TRIGGER IF EXISTS trg_document_versions_updated_at ON document_versions;
CREATE TRIGGER trg_document_versions_updated_at
    BEFORE UPDATE ON document_versions
    FOR EACH ROW EXECUTE FUNCTION set_updated_at();

DROP TRIGGER IF EXISTS trg_sync_jobs_updated_at ON sync_jobs;
CREATE TRIGGER trg_sync_jobs_updated_at
    BEFORE UPDATE ON sync_jobs
    FOR EACH ROW EXECUTE FUNCTION set_updated_at();

DROP TRIGGER IF EXISTS trg_document_chunks_updated_at ON document_chunks;
CREATE TRIGGER trg_document_chunks_updated_at
    BEFORE UPDATE ON document_chunks
    FOR EACH ROW EXECUTE FUNCTION set_updated_at();

